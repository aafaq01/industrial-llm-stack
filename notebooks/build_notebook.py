def md(text):
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": text.splitlines(keepends=True),
    }


def code(text):
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": text.splitlines(keepends=True),
    }


def build(out, embed, make_cells):
    """Write notebook `out` from make_cells(git_commit, embed_cell_source) -> cells, with the files in `embed`
    embedded (sha256 per file). git_commit gets "-dirty" if any embedded file differs from HEAD."""
    commit = (
        subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=False,
        ).stdout.strip()
        or "unknown"
    )
    dirty = subprocess.run(
        ["git", "-C", str(ROOT), "status", "--porcelain", *embed],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    commit += "-dirty" if dirty else ""
    files = {}
    for rel in embed:
        text = (ROOT / rel).read_text(encoding="utf-8")
        files[rel] = (hashlib.sha256(text.encode()).hexdigest(), text)
    cells = make_cells(commit, EMBED_CELL.format(files=json.dumps(files)))
    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    for i, c in enumerate(nb["cells"]):
        c["id"] = f"cell-{i:02d}"
    out.write_text(
        json.dumps(nb, indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    # Format with the same ruff as pre-commit so the hook leaves the generated file alone.
    ruff = ["uvx", "--python", "3.12", "ruff@0.16.10"]
    subprocess.run([*ruff, "check", "--fix", "-q", str(out)], check=True)
    subprocess.run([*ruff, "format", "-q", str(out)], check=True)
    print(f"wrote {out} ({commit})")


def main():
    def make_cells(commit, embed_cell):
        cells = [
            md(INTRO),
            code(CONFIG.format(git_commit=commit)),
            code(embed_cell),
            code(ENV_CELL),
            code(PREFLIGHT_CELL),
            md("## Install (estimate about 10 min, mostly downloads)"),
            code(INSTALL_CELL),
            code(HELPERS_CELL),
        ]
        for title, src in CELLS:
            cells += [md(f"## {title}"), code(src)]
        return cells + [md("## Summary"), code(SUMMARY_CELL)]

    build(ROOT / "notebooks" / "vllm_t4_benchmark.ipynb", EMBED, make_cells)


if __name__ == "__main__":
    main()
